def strip_artifacts(dispatch: str) -> str:
    """Remove template instruction artifacts from LLM output."""
    # Strip "Sample dispatch generated for format review" if the LLM included it
    dispatch = re.sub(
        r"> \*Sample dispatch generated for format review[^\n]*\n(\n)?",
        "", dispatch, count=1,
    )
    # Strip footer: "Generated by Hermes..." + "Review, edit, and publish..."
    dispatch = re.sub(
        r"\n?\*Generated by Hermes[^\n]*\n\*Review, edit, and publish[^\n]*\*",
        "", dispatch, count=1,
    )
    # Also strip standalone "Review, edit..." lines if footer was split
    dispatch = re.sub(
        r"\n\*Review, edit, and publish at your discretion[^\n]*\*",
        "", dispatch, count=1,
    )
    return dispatch.rstrip() + "\n"


