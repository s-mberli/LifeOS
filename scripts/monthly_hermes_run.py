def _run_fallback_pipeline(today: str) -> tuple[str, list[dict]]:
    """Original two-phase pipeline from raw TLDR articles.

    Used only when no weekly digest is available.
    Returns ``(dispatch_markdown, proposals_list)``.
    """
    from src.core.llm_client import parse_json_safely  # noqa: E402

    # Collect articles
    print("Collecting articles from last 30 days...")
    articles = collect_articles_from_notes(days=30)
    print(f"Found {len(articles)} unique article candidates.")

    if not articles:
        print("No articles found. Exiting.")
        return "", []

    # Phase 1: LLM selects top 5-7 stories from metadata
    candidates_text = build_candidates_prompt(articles)
    if len(candidates_text) > 60000:
        candidates_text = candidates_text[:60000] + "\n\n[... truncated ...]"

    selection_prompt = (
        "You are Hermes, a senior tech intelligence analyst.\n\n"  # nosec B608
        f"Below is a list of {len(articles)} articles from this month's tech newsletters.\n\n"
        "Pick the 7-10 most important, high-signal stories that a senior software "
        "engineer and CTO would care about.\n\n"
        "CRITICAL DIVERSITY RULE: You MUST select stories from at least 4 different "
        "newsletter sources/topics (look at the Source URL). Do not let AI and Tech "
        "dominate the entire list. Pick from InfoSec, Web Dev, Founders, Design, Data, etc.\n\n"
        "Prioritize:\n"
        "- Breakthrough research or paradigm shifts\n"
        "- Security advisories or CVEs\n"
        "- Major product launches or API changes\n"
        "- Architectural patterns or best practices\n\n"
        "Respond with ONLY a JSON array of the selected article numbers (1-indexed). "
        "Example: [3, 7, 12, 15, 22]\n\n"
        f"Articles:\n{candidates_text}"
    )

    print("Phase 1: Asking LLM to select top stories...")
    selection_response = call_llm(
        prompt=selection_prompt,
        system_prompt="You are a tech analyst. Respond with only a JSON array of numbers.",
        max_tokens=200,
        temperature=0.2,
    )

    if not selection_response:
        print("LLM selection failed. Falling back to 5 random articles.")
        selected_articles = random.sample(articles, min(5, len(articles)))
    else:
        print(f"LLM response: {selection_response}")  # codeql[py/clear-text-logging-sensitive-data]
        try:
            nums_match = re.search(r"\[[\d,\s]+\]", selection_response)
            if nums_match:
                indices = [int(x) for x in re.findall(r"\d+", nums_match.group())]
                selected_articles = [
                    articles[i - 1] for i in indices if 0 < i <= len(articles)
                ]
            else:
                selected_articles = random.sample(articles, min(5, len(articles)))
        except Exception:
            selected_articles = random.sample(articles, min(5, len(articles)))

    print(f"Selected {len(selected_articles)} articles for deep fetch.")

    # Phase 2: Fetch full text of selected articles
    enriched: list[dict] = []
    for art in selected_articles:
        print(f"  Fetching: {art['title'][:60]}...")
        try:
            _title, full_text = fetch_webpage_content(art["url"])
            if full_text and len(full_text) > FETCH_CAP_CHARS:
                full_text = full_text[:FETCH_CAP_CHARS] + "\n\n[... truncated ...]"
            art["full_text"] = full_text or art.get("summary", "")
            enriched.append(art)
        except Exception as exc:
            print(f"    Failed: {exc}")
            art["full_text"] = art.get("summary", "No content available.")
            enriched.append(art)

    # Build articles block for prompts
    articles_block = ""
    for i, art in enumerate(enriched, 1):
        articles_block += f"\n--- Article {i} ---\n"
        articles_block += f"Title: {art['title']}\n"
        articles_block += f"Source: {art['source']}\n"
        articles_block += f"URL: {art['url']}\n"
        articles_block += f"Full Text:\n{art['full_text']}\n"

    # Phase 2a: Proposals (only when explicitly enabled)
    proposals_list: list[dict] = []
    if os.environ.get("INCLUDE_PROPOSALS", "").lower() == "true":
        print("Phase 2a: Generating architecture proposals (INCLUDE_PROPOSALS=true)...")
        proposals_raw = call_llm(
            prompt=_build_proposal_prompt(articles_block, len(enriched)),
            system_prompt="You are Hermes, a brilliant CTO. Respond ONLY with valid JSON.",
            max_tokens=3000,
            temperature=0.2,
        )
        if proposals_raw:
            proposals_list = parse_json_safely(proposals_raw)
            if not isinstance(proposals_list, list):
                proposals_list = []
        if not proposals_list:
            print(
                "WARNING: LLM failed to generate proposals (or returned empty list). "
                "Skipping proposals.",
            )
    else:
        print("Proposals disabled (set INCLUDE_PROPOSALS=true to enable).")

    # Phase 2b: Dispatch generation
    print("Phase 2b: Generating dispatch...")
    dispatch = call_llm(
        prompt=_build_dispatch_prompt_fallback(articles_block, today, len(enriched)),
        system_prompt=(
            "You are Hermes, a brilliant CTO writing a weekly newsletter. "
            "Do not include literal instructions in your output."
        ),
        max_tokens=DISPATCH_MAX_TOKENS,
        temperature=DISPATCH_TEMPERATURE,
    )

    return dispatch or "", proposals_list


