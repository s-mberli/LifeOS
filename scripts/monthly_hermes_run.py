def find_latest_digest() -> Path | None:
    """Find the most recent weekly digest in DIGEST_DIR.

    Digest files are named ``tldr-weekly-YYYY-MM-DD-wYYYYWNN.md``
    and generated by :func:`weekly_tldr_process.main`.
    """
    if not DIGEST_DIR.exists():
        return None
    digests = sorted(DIGEST_DIR.glob("tldr-weekly-*.md"))
    return digests[-1] if digests else None


