def _proposal_output_path(proposal_dir: Path, filename: object) -> Path | None:
    """Return a draft path only for a plain filename inside the proposals dir."""
    if (
        not isinstance(filename, str)
        or not filename
        or filename in {".", ".."}
        or any(char in filename for char in "/\\:")
    ):
        return None

    if not filename.endswith(".md"):
        filename += ".md"
    candidate = proposal_dir / filename
    try:
        if not candidate.resolve().is_relative_to(proposal_dir.resolve()):
            return None
    except (OSError, RuntimeError):
        return None
    return candidate


@execute_with_repair(mode="background")
def run_weekly_pipeline() -> None:
    today = datetime.datetime.now().strftime("%Y-%m-%d")
    out_file = DRAFT_DIR / f"monthly_dispatch_{today}.md"
    source_file = out_file.with_suffix(".source.json")
    if any(path.exists() or path.is_symlink() for path in (out_file, source_file)):
        print(f"Existing draft or source record for {today}; skipping rerun.")
        return
    print("--- Starting Weekly Hermes Pipeline ---")

    # 1. Run outbox triage
    print("Running outbox triage...")
    triage_notes()

    # 2. Try digest-first approach; fall back to raw articles if no digest
    digest_path = find_latest_digest()
    digest_sha256: str | None = None
    proposals_list: list[dict] = []

    if digest_path:
        try:
            digest_display = digest_path.relative_to(BASE_DIR)
        except ValueError:
            digest_display = digest_path
        print(f"Found weekly digest: {digest_display}")
        digest_content = digest_path.read_text(encoding="utf-8")
        digest_sha256 = hashlib.sha256(digest_path.read_bytes()).hexdigest()

        # Collect article URLs for cross-referencing in the dispatch
        articles = collect_articles_from_notes(days=7)
        print(f"Collected {len(articles)} articles for URL metadata.")
        url_refs = build_url_reference(articles)

        # Generate dispatch from digest (single LLM call)
        print("Generating dispatch from weekly digest...")
        dispatch = call_llm(
            prompt=_build_dispatch_prompt_from_digest(digest_content, url_refs, today),
            system_prompt=(
                "You are Hermes, a brilliant CTO writing a weekly newsletter. "
                "Do not include literal instructions in your output."
            ),
            max_tokens=DISPATCH_MAX_TOKENS,
            temperature=DISPATCH_TEMPERATURE,
        )

        # Proposals (only when explicitly enabled — default: off)
        if os.environ.get("INCLUDE_PROPOSALS", "").lower() == "true":
            from src.core.llm_client import parse_json_safely  # noqa: E402

            print("Generating architecture proposals (INCLUDE_PROPOSALS=true)...")
            proposals_raw = call_llm(
                prompt=_build_proposal_prompt(
                    f"Digest content:\n{digest_content[:6000]}\n\n{url_refs}",
                    len(articles),
                ),
                system_prompt=(
                    "You are Hermes, a brilliant CTO. Respond ONLY with valid JSON."
                ),
                max_tokens=3000,
                temperature=0.2,
            )
            if proposals_raw:
                proposals_list = parse_json_safely(proposals_raw)
                if not isinstance(proposals_list, list):
                    proposals_list = []
    else:
        # Fallback: raw article pipeline
        print("No digest found. Falling back to raw article pipeline...")
        dispatch, proposals_list = _run_fallback_pipeline(today)

    # 3. Sanitise output
    dispatch = strip_artifacts(dispatch or "")

    if not dispatch:
        print(
            "WARNING: LLM failed to generate dispatch (possible content filter). "
            "Using placeholder.",
        )
        dispatch = (
            "_No dispatch generated this week due to content filters or API errors._"
        )

    # 4. Save dispatch locally
    out_dir = DRAFT_DIR
    out_dir.mkdir(parents=True, exist_ok=True)
    with out_file.open("x", encoding="utf-8") as output:
        output.write(dispatch)  # codeql[py/clear-text-storage-sensitive-data]
    source = {
        "digest": digest_path.relative_to(BASE_DIR).as_posix() if digest_path else None,
        "sha256": digest_sha256,
    }
    with source_file.open("x", encoding="utf-8") as output:
        output.write(json.dumps(source, indent=2) + "\n")
    print(f"✓ Monthly dispatch saved: {out_file.relative_to(BASE_DIR)}")

    # 5. Save proposals (if any were generated)
    if proposals_list:
        prop_dir = BASE_DIR / "data" / "inbox" / "proposals"
        prop_dir.mkdir(parents=True, exist_ok=True)
        for prop in proposals_list:
            filename = prop.get("filename", f"proposal_{today}.md")
            prop_file = _proposal_output_path(prop_dir, filename)
            if prop_file is None:
                print("WARNING: Skipping proposal with unsafe filename.")
                continue
            prop_file.write_text(
                prop.get("content", ""), encoding="utf-8",
            )  # codeql[py/clear-text-storage-sensitive-data]
            print(f"✓ Proposal saved: {prop_file.relative_to(BASE_DIR)}")  # codeql[py/clear-text-logging-sensitive-data]

    # 6. Update outbox DB
    if DB_PATH.exists():
        conn = get_db_connection(DB_PATH)
        cursor = conn.cursor()
        cursor.execute("""
            SELECT id FROM automation_outbox
            WHERE is_actionable = 1
              AND processed_at IS NOT NULL
              AND hermes_run_at IS NULL
        """)
        row_ids = [r[0] for r in cursor.fetchall()]
        if row_ids:
            now_str = (
                datetime.datetime.now(datetime.timezone.utc)
                .astimezone()
                .isoformat()
            )
            placeholders = ",".join("?" for _ in row_ids)
            cursor.execute(
                f"UPDATE automation_outbox SET hermes_run_at = ? WHERE id IN ({placeholders})",  # nosec B608
                [now_str] + row_ids,
            )
            conn.commit()
            print(f"✓ Marked {len(row_ids)} outbox items as processed.")
        conn.close()

    print("--- Pipeline Complete ---")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate a monthly dispatch draft.")
    parser.add_argument(
        "--publish-draft", metavar="PATH",
        help="Publish an existing reviewed draft with its unchanged fresh source digest.",
    )
    args = parser.parse_args(argv)
    if args.publish_draft is not None:
        return 0 if publish_existing_draft(args.publish_draft) else 1
    run_weekly_pipeline()
    return 0


if __name__ == "__main__":
    sys.exit(main())
